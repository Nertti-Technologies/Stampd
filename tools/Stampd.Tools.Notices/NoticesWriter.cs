using System.Security.Cryptography;
using System.Text;

namespace Stampd.Tools.Notices;

/// <summary>
/// Renders the notices file: a component index, then each distinct licence text and NOTICE text
/// once, listing every component it covers. Identical texts (for example the shared .NET notices
/// carried by dozens of Microsoft packages) are printed once instead of per package.
/// </summary>
internal static class NoticesWriter
{
    public static string Render(IReadOnlyList<Component> components)
    {
        var ordered = components.OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase)
                                .ThenBy(c => c.Version, StringComparer.Ordinal).ToList();
        var licenceTexts = Group(ordered, c => c.LicenseText is null ? [] : [c.LicenseText]);
        var noticeTexts = Group(ordered, c => c.Notices);

        var sb = new StringBuilder();
        sb.AppendLine("STAMPD THIRD-PARTY NOTICES");
        sb.AppendLine();
        sb.AppendLine("Stampd is licensed under the Apache License, Version 2.0 (see LICENSE). It uses the");
        sb.AppendLine("third-party components listed below, each under its own licence. This file is");
        sb.AppendLine("generated by tools/Stampd.Tools.Notices; do not edit it by hand.");
        sb.AppendLine();
        sb.AppendLine("COMPONENTS");
        sb.AppendLine(new string('=', 80));
        foreach (var c in ordered)
        {
            sb.Append(CultureInvariant($"{c.Name} {c.Version}  [{c.License}]"));
            sb.AppendLine(c.ProjectUrl is null ? "" : "  " + c.ProjectUrl);
            sb.AppendLine("    licence text: " + c.TextSource);
        }

        Section(sb, "LICENCE TEXTS", licenceTexts);
        Section(sb, "NOTICES SHIPPED BY COMPONENTS", noticeTexts);
        return sb.ToString().ReplaceLineEndings("\n");
    }

    private static List<(string Text, List<Component> Users)> Group(
        IEnumerable<Component> components, Func<Component, IEnumerable<string>> texts)
    {
        var groups = new Dictionary<string, (string Text, List<Component> Users)>(StringComparer.Ordinal);
        foreach (var c in components)
        foreach (string t in texts(c))
        {
            string normalized = t.ReplaceLineEndings("\n").Trim();
            string key = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(normalized)));
            if (!groups.TryGetValue(key, out var g)) groups[key] = g = (normalized, []);
            g.Users.Add(c);
        }
        return groups.Values.OrderBy(g => Label(g.Users[0]), StringComparer.OrdinalIgnoreCase).ToList();
    }

    private static void Section(StringBuilder sb, string title, List<(string Text, List<Component> Users)> groups)
    {
        sb.AppendLine();
        sb.AppendLine(title);
        sb.AppendLine(new string('=', 80));
        foreach (var (text, users) in groups)
        {
            sb.AppendLine();
            sb.AppendLine("Applies to: " + string.Join(", ", users.Select(Label).Distinct(StringComparer.Ordinal)));
            sb.AppendLine(new string('-', 80));
            sb.AppendLine(text);
        }
    }

    private static string Label(Component c) => $"{c.Name} {c.Version}";

    private static string CultureInvariant(FormattableString s) => FormattableString.Invariant(s);
}
